-- Every organisation's claims take their request's new key: the tenant wall binds
-- the owner too (FORCE) and no organisation is named here, so it is lifted for this
-- one statement and put back, in the migration's own transaction. Two open claims
-- on one order under the new fold can't both stand: see the top of this file. All
-- the words are in the message, as the log keeps an error's message and not its
-- hint, and the IDs come first, as a long line keeps only 128 characters of it. IDs,
-- never a reference (the key's own error would quote one).
ALTER TABLE spend_requests.requests NO FORCE ROW LEVEL SECURITY;
ALTER TABLE spend_requests.order_claims NO FORCE ROW LEVEL SECURITY;
DO $$
DECLARE
  one uuid;
  other uuid;
BEGIN
  UPDATE spend_requests.order_claims AS claim
    SET order_reference = request.order_key
    FROM spend_requests.requests AS request
    WHERE request.org_id = claim.org_id AND request.id = claim.request_id
      AND claim.order_reference <> request.order_key;
EXCEPTION WHEN unique_violation THEN
  SELECT a.request_id, b.request_id INTO one, other
    FROM spend_requests.order_claims AS a
    JOIN spend_requests.requests AS asked_a ON asked_a.org_id = a.org_id AND asked_a.id = a.request_id
    JOIN spend_requests.order_claims AS b ON b.org_id = a.org_id AND b.request_id > a.request_id
      AND (b.supplier_id = a.supplier_id OR b.payee_key = a.payee_key)
    JOIN spend_requests.requests AS asked_b ON asked_b.org_id = b.org_id AND asked_b.id = b.request_id
    WHERE a.released_at IS NULL AND b.released_at IS NULL AND asked_a.order_key = asked_b.order_key
    LIMIT 1;
  RAISE EXCEPTION 'Stopped: requests %, % are one order under the new case fold. This update changed nothing. Next: cancel one if it can be, or wait for a payment under way to fail, then release again; if both are paid or unknown, nothing in the app frees them: follow the top of 0067.', one, other
    USING ERRCODE = 'check_violation';
END;
$$;
