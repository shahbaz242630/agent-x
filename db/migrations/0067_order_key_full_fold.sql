-- PL-39 (ADR-006 §5, decision 6, SEC-DP-10): an order's canonical form folds
-- case by Unicode's own table, not the database's lower(). lower() is one
-- character to one, by the database's locale: straße and STRASSE were two
-- orders, as were ΣΑΣ and σας, so one invoice could be claimed twice.
--
-- Worked out here, in one function, as 0039's expression was: the request's
-- generated `order_key`, the duplicate check before the request exists and the
-- claim all call it, so no second copy can disagree with it, and no Node or ICU
-- upgrade can move a key. The method is Unicode's compatibility caseless match
-- (Core Spec 3.13, D146), written with NFKC: fold(NFD), NFKC, fold, NFKC.
--
-- The table is CaseFolding.txt 17.0.0, statuses C and F, sha-256
-- ff8d8fefbf123574205085d6714c36149eb946d717a0c585c27f0f4ef58c4183: the version
-- the app's edge accepts up to. It is written here, so it never changes with the
-- server, its locale or its version (casefold() is on 18 only, and takes its
-- table from the server). Unicode promises a folded character stays folded; a
-- later version would only add new letters, and adding them means a new
-- migration that re-keys, as this one does. Never edit this table in place.
--
-- One change from the table, for Turkish: İ, I, ı and i are one letter here.
-- Unicode's default keeps İ (as i with a dot above) and ı apart from i, so KIZ
-- and kız, or İNV and inv, would be two orders. Paying one invoice twice costs
-- more than refusing two whose numbers differ only by that dot.
--
-- What's still the server's: normalize(), from the tables Postgres ships. Unicode
-- promises a string of assigned characters normalises the same for ever, and the
-- edge refuses unassigned ones (visibleName). So the only risk is a character the
-- edge knows and the server doesn't. Today that is one: U+A7F1 (Unicode 17, a
-- modifier capital S; 18 knows Unicode 16), which the table folds to s itself, so
-- no later server can move its key. A test compares the edge's normalisation with
-- the server's and pins a digest of the server's, so an upgrade of Node or Postgres
-- that opens a new gap fails it first. If one still slipped by, the holdings check
-- compares each claim's key with the key worked out now, and raises the alarm.
--
-- Cyrillic а and Latin a stay two orders: they are different letters, and a
-- look-alike table is no case fold. (On the rail, 0043's `bank_key` looks at
-- what the bank would carry; that stays as it is.)
--
-- If this migration stops, its message names two requests whose open claims the new
-- fold makes one order. What happened: their references differed under lower() and
-- don't now. What broke: the release; this update changed nothing, and the version
-- running stays. What next, by where the two requests are:
-- - Either not handed off yet: cancel it, then release again.
-- - Handed off with its payment under way: wait. A payment that fails or is cancelled
--   frees its claim. Then release again.
-- - Both past that, paid or unknown: nothing in the app frees either. A paid order
--   keeps its claim for good, so it is never paid again, and a handed-off request
--   can't be cancelled. Production isn't live, so this can only be staging's test
--   data: a developer, as owner in one transaction, lifts the wall on order_claims,
--   disables claim_guard, sets released_at on one claim, and puts both back; the
--   holdings check then reports that request, as it should. On real money this would
--   be one invoice possibly paid twice: don't do this, take it to the bank first.
--
