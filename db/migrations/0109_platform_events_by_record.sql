-- agentx: no transaction (concurrent index)
-- S207 (GM-2, R-15): a session signed out of is signed on the platform chain as
-- `identity.session_ended`, naming the session by its record ID (`record`), and every
-- signed-in request asks whether its own session has such a record (sessions.ts), read in
-- the statement that finds the session. Through 0084's by-person index alone that read
-- would grow with every sign-out the person ever made. This index keys the action and the
-- record, as platform-events.ts compares it (`(details::jsonb ->> 'record')`, written out
-- exactly), so the read is a few index entries however long the chain. An event without
-- the fact has a null there. The platform chain is a global table, of no organisation
-- (0003): no org_id to lead with, and no table, column or grant changes.
--
-- Built concurrently, outside a transaction (the first line; migrate.ts), as 0084's and
-- 0103's: events go on being recorded while it builds. A build that fails leaves the index
-- not valid, which the guard reads as speed, not drift (schema-guard.ts), and the next run
-- drops it and builds it again.
CREATE INDEX CONCURRENTLY IF NOT EXISTS audit_events_by_record ON platform_controls.audit_events (action, (details::jsonb ->> 'record'));
